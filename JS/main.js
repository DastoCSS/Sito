// Language detection and application
function detectLanguage() {
    const userLang = navigator.language || navigator.userLanguage;
    return userLang.startsWith('it') ? 'it' : 'en';
}

function applyLanguage() {
    const detectedLang = detectLanguage();
    const lang = content[detectedLang];
    document.documentElement.lang = detectedLang;

    // Update UI elements
    const elements = {
        'ui-subtitle': lang.subtitle,
        'ui-booking-btn': lang.bookingBtn,
        'title-about': lang.titleAbout,
        'title-pricing': lang.titlePricing,
        'title-equipment': lang.titleEquipment,
        'title-services': lang.titleServices,
        'title-highlights': lang.titleHighlights,
        'title-music': lang.titleMusic,
        'title-booking': lang.titleBooking
    };

    Object.entries(elements).forEach(([id, text]) => {
        const el = document.getElementById(id);
        if (el) el.innerText = text;
    });

    // Update HTML content
    const htmlElements = {
        'text-about': lang.textAbout,
        'text-services': lang.textServices,
        'text-music': lang.textMusic,
        'text-booking': lang.textBooking
    };

    Object.entries(htmlElements).forEach(([id, html]) => {
        const el = document.getElementById(id);
        if (el) el.innerHTML = html;
    });
}

// Canvas animation
const canvas = document.getElementById('canvas-bg');
const ctx = canvas.getContext('2d', { alpha: false });
let w, h, blobs = [];
let animationId;
let lastTime = 0;
const fps = 30;
const fpsInterval = 1000 / fps;

const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
const isLowPowerDevice = /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent);
const blobCount = isLowPowerDevice ? 3 : 5;

function init() {
    w = canvas.width = innerWidth;
    h = canvas.height = innerHeight;
    
    blobs = [...Array(blobCount)].map(() => ({
        x: Math.random() * w,
        y: Math.random() * h,
        r: Math.random() * (isLowPowerDevice ? 150 : 250) + (isLowPowerDevice ? 100 : 200),
        vx: (Math.random() - 0.5) * (isLowPowerDevice ? 0.4 : 0.8),
        vy: (Math.random() - 0.5) * (isLowPowerDevice ? 0.4 : 0.8),
        c: ['#0a0a0a', '#1a0033', '#440011'][Math.floor(Math.random() * 3)]
    }));
}

function animate(currentTime) {
    if (!prefersReducedMotion) {
        const elapsed = currentTime - lastTime;
        
        if (elapsed > fpsInterval) {
            lastTime = currentTime - (elapsed % fpsInterval);
            
            ctx.fillStyle = '#050505';
            ctx.fillRect(0, 0, w, h);
            
            blobs.forEach(b => {
                b.x += b.vx;
                b.y += b.vy;
                if (b.x < 0 || b.x > w) b.vx *= -1;
                if (b.y < 0 || b.y > h) b.vy *= -1;
                
                ctx.beginPath();
                ctx.arc(b.x, b.y, b.r, 0, Math.PI * 2);
                ctx.fillStyle = b.c;
                ctx.fill();
            });
        }
        
        animationId = requestAnimationFrame(animate);
    }
}

// Image slider
let currentSlide = 0;
const track = document.getElementById('sliderTrack');

function nextSlide() {
    const slides = document.querySelectorAll('.slide');
    if (!track || slides.length === 0) return;
    currentSlide = (currentSlide + 1) % slides.length;
    track.style.transform = `translateX(-${currentSlide * 100}%)`;
}

let sliderInterval = setInterval(nextSlide, 4000);

// Visibility change handler
document.addEventListener('visibilitychange', () => {
    if (document.hidden) {
        clearInterval(sliderInterval);
        if (animationId) cancelAnimationFrame(animationId);
    } else {
        sliderInterval = setInterval(nextSlide, 4000);
        if (!prefersReducedMotion) animate(0);
    }
});

// Lightbox functions
function openReel(id) {
    const lb = document.getElementById('lightbox');
    const iframe = document.getElementById('lightbox-iframe');
    iframe.src = `https://www.instagram.com/reel/${id}/embed`;
    lb.style.display = 'flex';
    lb.setAttribute('aria-hidden', 'false');
    document.querySelector('.close-lightbox').focus();
    document.body.style.overflow = 'hidden';
}

function closeReel() {
    const lb = document.getElementById('lightbox');
    document.getElementById('lightbox-iframe').src = '';
    lb.style.display = 'none';
    lb.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
}

// Keyboard events
document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && document.getElementById('lightbox').style.display === 'flex') {
        closeReel();
    }
});

document.querySelectorAll('.reel').forEach(reel => {
    reel.addEventListener('keypress', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
            e.preventDefault();
            reel.click();
        }
    });
});

