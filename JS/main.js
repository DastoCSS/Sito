function applyLanguage(lang) {
    if (!translations[lang]) lang = 'en';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    const htmlRoot = document.getElementById('html-root');
    htmlRoot.setAttribute('lang', lang);
    if (lang === 'fa' || lang === 'ar') {
        htmlRoot.setAttribute('dir', 'rtl');
    } else {
        htmlRoot.setAttribute('dir', 'ltr');
    }
}

document.addEventListener('DOMContentLoaded', () => {
    
    // --- DOPPIO CONTROLLO IP PER AGGIRARE CENSURE NAZIONALI (es. IRAN) ---
    fetch('https://ipapi.co/json/') // 1. Prova il server principale
        .then(res => res.json())
        .then(data => {
            const countryCode = data.country_code;
            let targetLang = countryToLanguageMap[countryCode] || 'en';
            applyLanguage(targetLang);
        })
        .catch(() => {
            // 2. Se bloccato, prova il server di emergenza (senza limiti e open)
            fetch('https://get.geojs.io/v1/ip/country.json')
                .then(res => res.json())
                .then(data => {
                    const countryCode = data.country;
                    let targetLang = countryToLanguageMap[countryCode] || 'en';
                    applyLanguage(targetLang);
                })
                .catch(() => {
                    // 3. Ultima risorsa: Lingua di sistema del telefono/browser
                    const browserLang = navigator.language || navigator.userLanguage;
                    const shortLang = browserLang.substring(0, 2);
                    if (translations[shortLang]) {
                        applyLanguage(shortLang);
                    } else {
                        applyLanguage('en');
                    }
                });
        });

    // --- Effetto interattivo sulle carte ---
    const cards = document.querySelectorAll('.card');
    cards.forEach(card => {
        card.addEventListener('mousemove', e => {
            const rect = card.getBoundingClientRect();
            const x = e.clientX - rect.left;
            const y = e.clientY - rect.top;
            card.style.setProperty('--mouse-x', `${x}px`);
            card.style.setProperty('--mouse-y', `${y}px`);
        });
    });

    // --- Scroll Reveal ---
    const revealElements = document.querySelectorAll('[data-reveal]');
    const observerOptions = { root: null, rootMargin: '0px 0px -60px 0px', threshold: 0.1 };
    const revealObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('is-revealed');
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    revealElements.forEach(el => revealObserver.observe(el));
});
